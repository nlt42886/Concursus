export function getPlanById(planId: string): BibleReadingPlan | undefined {
  return ALL_PLANS.find(plan => plan.id === planId);
}

export function getDayReadings(planId: string, dayNumber: number) {
  const plan = getPlanById(planId);
  if (!plan) return null;
  return plan.dailyReadings.find(r => r.day === dayNumber) ?? null;
}

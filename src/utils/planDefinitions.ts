import { BibleReadingPlan, Passage } from '../types/bible.types';

function p(bookCode: string, bookName: string, chapter: number, startVerse?: number, endVerse?: number): Passage {
  const display = startVerse
    ? endVerse
      ? `${bookName} ${chapter}:${startVerse}-${endVerse}`
      : `${bookName} ${chapter}:${startVerse}`
    : `${bookName} ${chapter}`;
  const apiBase = bookName.toLowerCase().replace(/\s/g, '+');
  const apiQuery = startVerse
    ? endVerse
      ? `${apiBase}+${chapter}:${startVerse}-${endVerse}`
      : `${apiBase}+${chapter}:${startVerse}`
    : `${apiBase}+${chapter}`;
  return {
    id: startVerse ? `${bookCode}.${chapter}.${startVerse}` : `${bookCode}.${chapter}`,
    bookCode,
    bookName,
    chapter,
    startVerse,
    endVerse,
    displayText: display,
    apiQuery,
  };
}

